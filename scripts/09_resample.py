"""Sentence-level resampling: truncate a chain of thought and re-run the rest, many times.

    python scripts/09_resample.py --mode brake     --run qwen3.5-27b_20260823_223518
    python scripts/09_resample.py --mode insertion --run qwen3.5-27b_20260823_223518
    python scripts/09_resample.py --mode brake --dry-run          # pick targets, print them, no GPU

Measures the causal contribution of one sentence: p(outcome | prefix up to sentence k) against the
same for k-1. Two modes.

  brake      Rollouts that landed on the UNFAVOURED side and contain a refusal ("I will not...",
             "stop trying...") late in the trace. Resample a window of cut points AROUND that
             sentence. Is the honest landing already settled before the refusal is written, or is it
             a coin flip? 20/30 honest continuations means the refusal reports a decision already
             made; 3/30 means the 24% honest rate is a lottery.

             The neighbour window is not decoration. p(favoured) drifts upward toward the end of any
             trace simply because less is left to change, so a jump at the refusal means nothing
             unless it is larger than the jumps on either side of it.

  targets    Hand-picked cut points, named on the command line, with a neighbour window around
             each. The other modes find their own targets by regex; this one takes them from a
             human who has read the traces. Use it to contrast two candidate drivers inside a
             SINGLE rollout — everything else about the trace is then held constant, which no
             cross-rollout comparison can do.

               --mode targets --targets "above_good/74@110,115 above_good/19@179,191"

             Windows are unioned and de-duplicated, so overlapping targets cost nothing extra.

  insertion  Rollouts that landed on the FAVOURED side with no refusal. Cut at a fixed depth and
             resample three arms: unchanged, + an accuracy re-assertion, + a conflict-naming
             sentence. Correlational resampling can only describe; this can find a mitigation.

Why not the "most accurate point estimate" phrase, which was the original target: it appears in
177/200 main incentive rollouts at a median depth of 4%, and P(favoured) is 0.83 / 0.84 / 0.80 for
rollouts that never / early-only / late mention it. It is an echo of the prompt, not a brake.

Continuations are generated by prefilling the chat template plus the partial reasoning and letting
the model finish inside the thinking block — NOT via llm.chat, which would start a fresh turn.
Sampling temperature must match the original run or the curve measures temperature, not the sentence.
"""

