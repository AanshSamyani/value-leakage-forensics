def merge_passages(sents: list[str], min_chars: int) -> list[str]:
    """Glue consecutive sentences into passages of at least min_chars.

    Our CoT is a dense bulleted list, so the sentence splitter yields ~70-character units — one
    bullet each, rarely load-bearing alone. The paper scores "each sentence (or paragraph)", and a
    coarser unit is also the better statistical trade: for a fixed compute budget, fewer cut points
    buys more samples each, and the 95% CI on the difference between adjacent prefixes is
    1.96*sqrt(0.5/k) — +/-0.28 at k=25, +/-0.12 at k=125. The paper's largest score was +0.207, so
    a fine-grained sweep at low k could not have detected their own result.
    """
    out: list[str] = []
    for x in sents:
        if out and len(out[-1]) < min_chars:
            out[-1] += x
        else:
            out.append(x)
    return out


def last_open(sents: list[str], final: float, min_chars_after: int) -> int | None:
    """The largest cut index at which the answer is not yet on the page and enough reasoning remains."""
    first = next((j for j in range(len(sents)) if already_committed(sents[j], final)), len(sents))
    for k in range(min(first, len(sents) - 1), 0, -1):
        if len("".join(sents[k:])) >= min_chars_after:
            return k
    return None


def pick_sweep_target(run_dir: Path, spec: str, min_chars: int) -> list[dict]:
    """mode=sweep: one named rollout, cut at every passage boundary. spec is 'cond/index'."""
    cond, idx = spec.split("/")
    idx = int(idx)
    blob = json.loads((run_dir / f"{cond}.json").read_text())
    est = json.loads((run_dir / "estimates.json").read_text())
    T = float(json.loads((run_dir / "threshold.json").read_text())["threshold"])
    row = next(r for r in blob["rows"] if r["i"] == idx and "error" not in r)
    e = float(est[cond][idx])
    up = good_is_above(cond)
    passages = merge_passages(split_sentences(row["reasoning"] or ""), min_chars)
    return [dict(cond=cond, i=idx, prompt=blob["prompt"], sents=passages, k=0, T=T, up=up,
                 final=e, favoured=(e > T) == up, target=f"full sweep of {len(passages)} passages",
                 committed=False, chars_after=len("".join(passages)),
                 nums_after=len(big_numbers("".join(passages))))]


def parse_target_spec(spec: str) -> list[tuple[str, int, list[int]]]:
    """'above_good/74@110,115 below_good/64@124' -> [('above_good', 74, [110, 115]), ...]"""
    out = []
    for chunk in re.split(r"[\s;]+", spec.strip()):
        if not chunk:
            continue
        where, _, ks = chunk.partition("@")
        cond, _, idx = where.partition("/")
        if not ks:
            raise SystemExit(f"target {chunk!r} names no cut points (want cond/index@k1,k2)")
        out.append((cond, int(idx), sorted({int(k) for k in ks.split(",")})))
    return out


def pick_explicit_targets(run_dir: Path, spec: str) -> list[dict]:
    """mode=targets: cut points chosen by hand, one dict per rollout.

    No filtering — the caller has read the trace and picked deliberately. Commitment is still
    CHECKED and reported, because a cut after the answer is on the page measures nothing and that
    is worth seeing before spending six GPU-hours, but it is not grounds for silent rejection.
    """
    est = json.loads((run_dir / "estimates.json").read_text())
    T = float(json.loads((run_dir / "threshold.json").read_text())["threshold"])
    out = []
    for cond, i, ks in parse_target_spec(spec):
        blob = json.loads((run_dir / f"{cond}.json").read_text())
        row = next((r for r in blob["rows"] if r["i"] == i and "error" not in r), None)
        if row is None:
            raise SystemExit(f"{cond}/#{i} not found (or errored) in {run_dir.name}")
        e = float(est[cond][i])
        up = good_is_above(cond)
        sents = split_sentences(row["reasoning"] or "")
        bad = [k for k in ks if not 0 < k < len(sents)]
        if bad:
            raise SystemExit(f"{cond}/#{i} has {len(sents)} sentences; cut(s) {bad} out of range")
        out.append(dict(cond=cond, i=i, prompt=blob["prompt"], sents=sents, k=ks[0], ks=ks, T=T,
                        up=up, final=e, favoured=(e > T) == up,
                        target=f"{len(ks)} hand-picked cut(s): {ks}",
                        committed=already_committed("".join(sents[:min(ks)]), e),
                        chars_after=len("".join(sents[min(ks):])),
                        nums_after=len(big_numbers("".join(sents[min(ks):])))))
    return out


def target_cuts(t: dict, window: int) -> list[int]:
    """Union of the +/-window neighbourhoods of every named cut, de-duplicated and sorted."""
    n = len(t["sents"])
    return sorted({c for k in t["ks"]
                   for c in range(max(0, k - window), min(n, k + window + 1))})


def pick_targets(run_dir: Path, mode: str, limit: int, tail: float, min_sents: int,
                 max_depth: float = 0.90, require_open: bool = True,
                 min_chars_after: int = 3000) -> list[dict]:
    """max_depth caps how late the cut may sit: a refusal at 99% of the way through leaves almost no
    reasoning to resample, so the measurement collapses into "was the answer already written"."""
    est = json.loads((run_dir / "estimates.json").read_text())
    T = float(json.loads((run_dir / "threshold.json").read_text())["threshold"])
    out = []
    for cond in ("above_good", "below_good"):
        p = run_dir / f"{cond}.json"
        if not p.exists():
            continue
        blob = json.loads(p.read_text())
        up = good_is_above(cond)
        for r in blob["rows"]:
            if "error" in r:
                continue
            i = r["i"]
            e = est.get(cond, [None] * (i + 1))[i] if i < len(est.get(cond, [])) else None
            if e is None:
                continue
            favoured = (float(e) > T) == up
            sents = split_sentences(r.get("reasoning") or "")
            if len(sents) < min_sents:
                continue
            if mode == "brake":
                if favoured:
                    continue                      # we want the ones that stayed honest
                lo = int(len(sents) * tail)
                hi = int(len(sents) * max_depth)
                hits = [k for k in range(lo, hi) if REFUSAL.search(sents[k])]
                if not hits:
                    continue
                k = hits[-1]                      # the last refusal before it commits
            else:
                if not favoured:
                    continue                      # we want the ones that leaked
                if any(REFUSAL.search(s) for s in sents[int(len(sents) * tail):]):
                    continue                      # ...and had no brake of their own
                # Cut at the LAST moment the answer is still open, not a fixed depth. A blind 60% cut
                # lands mid-arithmetic and, worse, often lands after the number is already written —
                # that alone disqualified 9 of 13 donors. The last open sentence is both the most
                # informative place to insert and the one that keeps the most donors.
                k = last_open(sents, float(e), min_chars_after)
                if k is None:
                    continue
            pre, post = "".join(sents[:k]), "".join(sents[k:])
            committed = already_committed(pre, float(e))
            if require_open and committed:
                continue
            if len(post) < min_chars_after:
                continue
            out.append(dict(cond=cond, i=i, prompt=blob["prompt"], sents=sents, k=k, T=T, up=up,
                            final=float(e), favoured=favoured, target=sents[k].strip(),
                            committed=committed, chars_after=len(post),
                            nums_after=len(big_numbers(post))))
    # most live reasoning left after the cut first — those have the most room to change
    out.sort(key=lambda d: -d["nums_after"])
    return out[:limit]


def build_units(targets, mode, window, n_samples, tok, stride=1):
    """One unit = (prefix text, label). Every unit is sampled n_samples times."""
    units = []
    for t in targets:
        base = chat_prefix(tok, t["prompt"])
        if mode == "sweep":
            # cuts at every passage boundary: 0 (nothing), 1, ..., n. The "after" distribution for
            # passage j IS the "before" for j+1, so n+1 prefixes cover every score.
            for j in range(0, len(t["sents"]) + 1, stride):
                partial = "".join(t["sents"][:j])
                units.append(dict(tid=id(t), cond=t["cond"], i=t["i"], k=0, cut=j, rel=j,
                                  arm="cut", prefix=base + partial, partial=partial))
        elif mode == "targets":
            for j in target_cuts(t, window):
                partial = "".join(t["sents"][:j])          # cut BEFORE sentence j
                near = min(t["ks"], key=lambda k: (abs(j - k), k))
                units.append(dict(tid=id(t), cond=t["cond"], i=t["i"], k=near, cut=j,
                                  rel=j - near, arm="cut", prefix=base + partial, partial=partial))
        elif mode == "brake":
            lo, hi = max(0, t["k"] - window), min(len(t["sents"]) - 1, t["k"] + window)
            for j in range(lo, hi + 1):
                partial = "".join(t["sents"][:j])          # cut BEFORE sentence j
                units.append(dict(tid=id(t), cond=t["cond"], i=t["i"], k=t["k"], cut=j,
                                  rel=j - t["k"], arm="cut", prefix=base + partial, partial=partial))
        else:
            partial = "".join(t["sents"][:t["k"]])
            for arm, ins in INSERTIONS.items():
                pre = partial + ((" " + ins + " ") if ins else "")
                units.append(dict(tid=id(t), cond=t["cond"], i=t["i"], k=t["k"], cut=t["k"],
                                  rel=0, arm=arm, prefix=base + pre, partial=pre))
    for u in units:
        u["n"] = n_samples
    return units


# --------------------------------------------------------------------------- main

def n_prefixes(t, mode, window):
    if mode == "targets":
        return len(target_cuts(t, window))
    if mode != "brake":
        return len(INSERTIONS)
    lo, hi = max(0, t["k"] - window), min(len(t["sents"]) - 1, t["k"] + window)
    return hi - lo + 1


def prepare(mode: str, run_dir: Path, args, tok):
    """Select targets, and build prefixes unless tok is None (--dry-run, which needs no tokenizer —
    transformers is a pod dependency and the preview has to work on a laptop)."""
    if mode == "sweep":
        targets = pick_sweep_target(run_dir, args.target, args.min_passage_chars)
    elif mode == "targets":
        targets = pick_explicit_targets(run_dir, args.targets)
    else:
        targets = pick_targets(run_dir, mode, args.limit, args.tail, args.min_sentences,
                               args.max_depth, not args.allow_committed, args.min_chars_after)
    print(f"\n=== {mode}: {len(targets)} target rollouts in {run_dir.name}", flush=True)
    if not targets:
        return None, None
    if mode == "targets":
        print(f"{'rollout':<18} {'sents':>6} {'cut':>6} {'depth':>6} {'committed':>10}  sentence")
        print("-" * 118)
        hours = 0.0
        for t in targets:
            for k in t["ks"]:
                pre = "".join(t["sents"][:k])
                print(f"{t['cond'] + '/#' + str(t['i']):<18} {len(t['sents']):>6} {k:>6} "
                      f"{k / len(t['sents']):>5.0%} {'YES' if already_committed(pre, t['final']) else 'no':>10}  "
                      f"{t['sents'][k].strip()[:60]}")
            hours += sum(len("".join(t["sents"][c:])) for c in target_cuts(t, args.window))
        hours = hours * args.samples / CHARS_PER_SEC / 3600
        ncut = sum(n_prefixes(t, mode, args.window) for t in targets)
        floor = 1.96 * (0.5 / args.samples) ** 0.5
        print(f"\n  {ncut} cut points (+/-{args.window} around each named cut, unioned) "
              f"x k={args.samples} = {ncut * args.samples:,} continuations")
        print(f"  estimated generation time ~{hours:.1f} h at {CHARS_PER_SEC:,.0f} chars/s")
        print(f"  a resampling score is only detectable above +/-{floor:.3f} at k={args.samples}")
        if tok is None:
            return targets, []
        units = build_units(targets, mode, args.window, args.samples, tok, args.stride)
        return targets, units
    for t in targets:
        print(f"  [{t['cond']}/#{t['i']}] {len(t['sents'])} sentences, cut at k={t['k']} "
              f"({t['k']/len(t['sents']):.0%} in), final {t['final']:,.0f} "
              f"({'favoured' if t['favoured'] else 'UNFAVOURED'})  |  {t['chars_after']:,} chars and "
              f"{t['nums_after']} candidate numbers still to come"
              f"{'  [ANSWER ALREADY COMMITTED]' if t['committed'] else ''}")
        print(f"      target sentence: {t['target'][:150]}")
    if tok is None:
        n = (sum(len(t["sents"]) // args.stride + 1 for t in targets) if mode == "sweep"
             else sum(n_prefixes(t, mode, args.window) for t in targets))
        print(f"  -> {n} prefixes x {args.samples} samples = {n * args.samples:,} continuations",
              flush=True)
        return targets, []
    units = build_units(targets, mode, args.window, args.samples, tok, args.stride)
    print(f"  -> {len(units)} prefixes x {args.samples} samples = "
          f"{sum(u['n'] for u in units):,} continuations", flush=True)
    return targets, units


async def run_mode(mode: str, run_dir: Path, args, sampler, targets, units):
    flat = [(ui, u) for ui, u in enumerate(units) for _ in range(u["n"])]
    out_path = run_dir / "analysis" / f"resample_{mode}.json"
    meta = {"mode": mode, "run": run_dir.name,
            "config": {k: getattr(args, k) for k in
                       ("samples", "window", "tail", "temperature", "max_tokens", "limit")}
                       | ({"targets": args.targets} if mode == "targets" else {}),
            "targets": [{k: v for k, v in t.items() if k != "sents"} for t in targets],
            "units": [{k: v for k, v in u.items() if k != "prefix"} for u in units]}
    results: list[dict] = []
    if getattr(args, "resume", False) and out_path.exists():
        prev = json.loads(out_path.read_text())
        same = [{k: v for k, v in u.items() if k != "prefix"} for u in units] == prev.get("units")
        if same and prev.get("results"):
            results = prev["results"]
            print(f"resuming {mode}: {len(results)}/{len(flat)} continuations already on disk")
        elif prev.get("results"):
            print(f"NOT resuming {mode}: the unit list changed since {out_path.name} was written")
    resumed = len(results)
    t0 = time()
    for start in range(resumed, len(flat), args.chunk):
        batch = flat[start:start + args.chunk]
        print(f"[{datetime.now():%H:%M:%S}] {mode}: submitting {len(batch)} continuations "
              f"({start + len(batch)}/{len(flat)})...", flush=True)
        outs = sampler.generate_raw([u["prefix"] for _, u in batch], max_tokens=args.max_tokens,
                                    temperature=args.temperature, top_p=args.top_p, use_tqdm=True)
        for (ui, u), o in zip(batch, outs):
            comp = o.outputs[0].text or ""
            results.append(dict(unit=ui, cond=u["cond"], i=u["i"], k=u["k"], cut=u["cut"],
                                rel=u["rel"], arm=u["arm"], answer=final_answer(u["partial"], comp),
                                tokens=len(o.outputs[0].token_ids),
                                truncated=str(o.outputs[0].finish_reason).startswith("length")))
        write_json(out_path, {**meta, "results": results})
        done, el = start + len(batch), time() - t0
        rate_ = (done - resumed) / el          # this session's rate, not diluted by resumed work
        eta = timedelta(seconds=int((len(flat) - done) / rate_)) if rate_ > 0 else "?"
        trunc = sum(1 for r in results if r["truncated"])
        print(f"[{datetime.now():%H:%M:%S}] {mode}: {done}/{len(flat)}  "
              f"elapsed {timedelta(seconds=int(el))}  eta {eta}  ({trunc} truncated)", flush=True)

    from forensics.judges.anthropic_judge import AnthropicJudge
    from forensics.judges.prompts_paper import NUMBER_JUDGE_PROMPT, parse_tagged_estimate
    judge = AnthropicJudge(model=args.judge_model,
                           cache_dir=run_dir / "judge_cache" / f"resample_{mode}",
                           max_concurrent=args.judge_concurrency)
    prompts = {str(n): NUMBER_JUDGE_PROMPT.format(llm_text=r["answer"])
               for n, r in enumerate(results) if (r["answer"] or "").strip()}
    res = await judge.run(prompts, max_tokens=256, desc=f"resample:{mode}")
    for n, v in res.items():
        results[int(n)]["estimate"] = parse_tagged_estimate(v.get("text")) if "text" in v else None
    print(judge.report())

    by = {(t["cond"], t["i"]): t for t in targets}
    for r in results:
        t = by[(r["cond"], r["i"])]
        e = r.get("estimate")
        r["favoured"] = None if e is None else ((float(e) > t["T"]) == t["up"])
    write_json(out_path, {**meta, "results": results})
    print(f"\nwrote {out_path}")
    summarise(results, mode, targets)


async def main_async(args):
    run_dir = resolve_run_dir(args.run)
    modes = ["brake", "insertion"] if args.mode == "both" else [args.mode]
    if args.mode == "targets" and not args.targets:
        raise SystemExit("--mode targets needs --targets 'cond/idx@k1,k2 ...'")

    cfg = json.loads((run_dir / "config.json").read_text())
    model = args.model or cfg.get("model_id") or cfg["model"]
    tok = None
    if not args.dry_run:
        from transformers import AutoTokenizer   # pod-only dependency; --dry-run must not need it
        tok = AutoTokenizer.from_pretrained(model, trust_remote_code=True)

    prepared = {}
    for m in modes:
        t, u = prepare(m, run_dir, args, tok)
        if t:
            prepared[m] = (t, u)
    if not prepared:
        raise SystemExit("no targets matched in any mode")
    if args.dry_run:
        print("\n(dry run — nothing generated)")
        return

    from forensics.samplers.vllm_offline import VLLMOfflineSampler
    print(f"\nbooting vLLM once for {len(prepared)} mode(s): {model}", flush=True)
    t_boot = time()
    sampler = VLLMOfflineSampler(model=model, max_tokens=args.max_tokens, temperature=args.temperature,
                                 top_p=args.top_p, max_model_len=args.max_model_len,
                                 gpu_memory_utilization=args.gpu_mem, max_num_seqs=args.max_num_seqs)
    print(f"engine up in {timedelta(seconds=int(time() - t_boot))}", flush=True)
    for m, (t, u) in prepared.items():
        await run_mode(m, run_dir, args, sampler, t, u)
    print(f"\n=== DONE ({datetime.now():%Y-%m-%d %H:%M:%S})")


def summarise(results, mode, targets=None):
    from forensics.stats import wilson_ci
    ok = [r for r in results if r.get("favoured") is not None]
    print(f"\n{len(ok)}/{len(results)} continuations produced a parseable estimate")
    if mode == "sweep":
        import numpy as np
        by = {}
        for r in ok:
            by.setdefault(r["cut"], []).append(r["favoured"])
        cuts = sorted(by)
        rate = {c: float(np.mean(by[c])) for c in cuts}
        print("\nP(favoured) after each cut  (cut j = prefix of the first j passages)")
        print(f"{'cut':>5} {'n':>5} {'P(fav)':>8} {'95% CI':>16}  {'score of passage j':>19}")
        print("-" * 62)
        for a, b in zip(cuts, cuts[1:] + [None]):
            k = sum(by[a])
            lo, hi = wilson_ci(k, len(by[a]))
            sc = f"{rate[b] - rate[a]:+.3f}" if b is not None else ""
            print(f"{a:>5} {len(by[a]):>5} {rate[a]:>8.3f} [{lo:.2f}, {hi:.2f}] {sc:>19}")
        # the paper's resampling score: after-minus-before for each passage
        sc = [(rate[b] - rate[a], a) for a, b in zip(cuts, cuts[1:])]
        sc.sort(key=lambda x: -abs(x[0]))
        print("\nLargest |resampling score| — the passages that moved the outcome:")
        for v, j in sc[:10]:
            txt = ""
            if targets:
                p_ = targets[0]["sents"]
                txt = p_[j].strip().replace("\n", " / ")[:110] if j < len(p_) else ""
            print(f"  passage {j:>3}  {v:+.3f}   {txt}")
        return
    if mode == "targets":
        import numpy as np
        by_roll: dict = {}
        for r in ok:
            by_roll.setdefault((r["cond"], r["i"]), {}).setdefault(r["cut"], []).append(r["favoured"])
        named = {(t["cond"], t["i"]): t["ks"] for t in (targets or [])}
        sents = {(t["cond"], t["i"]): t["sents"] for t in (targets or [])}
        floor = 1.96 * (0.5 / max(1, len(ok) // max(1, sum(len(v) for v in by_roll.values())))) ** 0.5
        for key_, cuts_d in by_roll.items():
            cuts = sorted(cuts_d)
            rate = {c: float(np.mean(cuts_d[c])) for c in cuts}
            print(f"\n=== {key_[0]}/#{key_[1]}")
            print(f"{'cut':>5} {'n':>5} {'P(fav)':>8} {'95% CI':>16} {'score':>9}   sentence")
            print("-" * 112)
            for a, b in zip(cuts, cuts[1:] + [None]):
                lo, hi = wilson_ci(sum(cuts_d[a]), len(cuts_d[a]))
                # score of sentence a = P(fav | prefix incl. a) - P(fav | prefix ending a-1),
                # i.e. the step from cut a to cut a+1. Only defined when both cuts were sampled.
                sc = f"{rate[b] - rate[a]:+.3f}" if b == a + 1 else ""
                star = " *" if a in named.get(key_, []) else "  "
                txt = sents[key_][a].strip().replace("\n", " / ")[:52] if a < len(sents[key_]) else ""
                print(f"{a:>5}{star} {len(cuts_d[a]):>4} {rate[a]:>8.3f} [{lo:.2f}, {hi:.2f}] "
                      f"{sc:>9}   {txt}")
            print("  * = hand-picked target. A named cut's score means something only if it beats "
                  f"the neighbour steps around it (drift floor ~+/-{floor:.2f}).")
        return
    key = (lambda r: r["rel"]) if mode == "brake" else (lambda r: r["arm"])
    hdr = "offset from the target sentence" if mode == "brake" else "arm"
    groups: dict = {}
    for r in ok:
        groups.setdefault(key(r), []).append(r["favoured"])
    print(f"\n{hdr:<32} {'n':>5} {'P(favoured)':>12} {'95% CI':>16}")
    print("-" * 70)
    for g in sorted(groups, key=lambda x: (isinstance(x, str), x)):
        v = groups[g]
        k = sum(v)
        lo, hi = wilson_ci(k, len(v))
        lab = (f"cut {g:+d} sentences" if isinstance(g, int) else g)
        print(f"{lab:<32} {len(v):>5} {k/len(v):>12.2f} [{lo:.2f}, {hi:.2f}]")
    if mode == "brake":
        print("\nThe step from -1 to 0 is the refusal sentence's own effect; the other steps are the "
              "local drift it has to beat.")


